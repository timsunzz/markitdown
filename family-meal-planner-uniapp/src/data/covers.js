/** 返回菜品的 emoji 配图字符：先查登记表，再按菜名关键词匹配，最后按类别兜底 */
function emojiFor(recipe) {
  if (EMOJIS[recipe.id]) return EMOJIS[recipe.id];
  const name = recipe.name || '';
  for (let i = 0; i < KEYWORD_EMOJIS.length; i++) {
    if (name.indexOf(KEYWORD_EMOJIS[i][0]) >= 0) return KEYWORD_EMOJIS[i][1];
  }
  return TYPE_FALLBACK[recipe.type] || '🍽️';
}

