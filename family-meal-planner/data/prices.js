/** 单个食材的预估价（元）；无价格数据或调味品返回 0 */
function priceFor(name, amount) {
  const unit = PRICES[name];
  if (!unit || !amount) return 0;
  return unit * amount;
}

/** 一道菜按份数系数放大后的预估成本（元，不含家中常备调味品） */
function dishCost(recipe, factor) {
  let sum = 0;
  (recipe.ingredients || []).forEach((ing) => {
    if (ing.pantry) return;
    sum += priceFor(ing.name, (ing.amount || 0) * factor);
  });
  return Math.round(sum * 10) / 10;
}

/** 一天菜单的总预估花费（元）；午晚餐按份量加大倍率计价 */
function dayCost(menu, factor, portionBoost) {
  const boost = portionBoost || 1;
  let sum = 0;
  ['breakfast', 'lunch', 'dinner'].forEach((meal) => {
    const f = meal === 'breakfast' ? factor : factor * boost;
    (menu[meal] || []).forEach((r) => {
      sum += dishCost(r, f);
    });
  });
  return Math.round(sum);
}

